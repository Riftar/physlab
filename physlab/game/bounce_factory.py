# ================================================================ 1.1 Bounce Flap

def run_bounce_flap(k, fx, thresholds=None):
    """Drop onto the pad, bounce UP through the one-way flap, don't touch the duct."""
    r, h0 = BALL_R, k["hatch"]
    e = bounce.RESTITUTION["rubber"][k["pad"]]
    hf, hp = fx["flap"], fx["flap"] + fx["duct_gap"]
    x0, x1 = FLAP_X
    segs = [(-0.3, 0.0, 1.5, 0.0, e, "pad"),
            (DUCT_X[0], hp, DUCT_X[1], hp, 0.8, "duct"),
            (-0.08, 0.0, -0.08, 5.0, E_WOOD, "hatch wall")]
    state = {"above": False}

    def through(x, y, vx, vy):
        if y - r > hf and x0 < x < x1 and vy > 0:
            state["above"] = True
        return state["above"] and vy < 0          # at the top, above the flap: it will land on it

    out = tracer.trace(0.0, h0 + r, FEED_U, 0.0, BALL["mass"], r, BALL_K, segs=segs,
                       zones=[("through", through)], tmax=4.0, stop_hits=3)
    names = [h["name"] for h in out["hits"]]
    apex = None
    if "pad" in names:
        t_pad = next(h["t"] for h in out["hits"] if h["name"] == "pad")
        ys = [f["y"] for f in out["frames"] if f["t"] >= t_pad]
        apex = round(max(ys) - r, 3) if ys else None
    frames = out["frames"]
    ok = out["outcome"] == "through" and "duct" not in names
    if ok:             # it drops onto the closed flap and settles on the shelf
        land = tracer.trace(out["x"], out["y"], out["vx"], out["vy"], BALL["mass"], r, BALL_K,
                            segs=[(x0, hf, SHELF_END - O_FLAP[0], hf, 0.3, "flap")] + segs[1:],
                            tmax=0.6)
        frames = frames + [dict(f, t=round(out["t"] + f["t"], 4)) for f in land["frames"][1:]]
    if "duct" in names:
        reason = "CLANG! It hit the hot duct - the bounce was too high (%.2f m)." % (apex or 0)
    elif not ok:
        reason = "It bounced to %.2f m but the flap is at %.2f m - not high enough." % (apex or 0, hf)
    else:
        reason = "Up through the flap: the bounce reached %.2f m (the flap is at %.2f m)." % (apex, hf)
    low = (thresholds or {}).get("low_drop")
    ideal = e * e * h0
    h_low = (thresholds or {}).get("h_low", h0)
    score = _score(ok, SCORE_MAX - H_COST * (h0 - h_low))
    return {
        "ok": ok, "reason": reason, "metric": apex, "unit": "m", "predicted": apex,
        "score": score,
        "score_parts": [{"label": "drop height", "value": "%.2f m" % h0,
                         "note": "-40 for every 10 cm above the lowest drop that works"}],
        "mastery": bool(ok and low is not None and h0 <= low + 1e-9),
        "frames": _world(frames, O_FLAP),
        "viz": {"apex": apex, "e": e, "ideal": round(ideal, 3)},
        "formula": [{"expr": "h1 = e^2 * h0", "values": {"e": e, "h0": h0, "e^2 * h0 (no air)": round(ideal, 3),
                                                         "h1 measured": apex}},
                    {"expr": "v = sqrt(2*g*h)", "values": {"h": h0, "v": round(math.sqrt(2 * G * h0), 2)}}],
        "lab": [{"title": "Bounces: the same drop in the lab",
                 "route": "#/bounce?" + _hash([("ball", "rubber"), ("surface", k["pad"]), ("height", h0)])},
                {"title": "Sandbox: try other balls on this pad",
                 "route": "#/sandbox/bounce?w=" + quote(json.dumps({"balls": ["rubber", "steel"], "surface": k["pad"],
                                                                    "height": h0}, separators=(",", ":")))}],
    }


# ================================================================ 1.2 Salt Canal

def brine(bags, litres):
    """Salt per litre, and the canal water it makes."""
    s = bags * 1000.0 / litres
    water = next(f for f in FLUIDS if f["id"] == "water")
    return s, (buoyancy.salt_water(water, s) if s > 0 else dict(water))


def delivery_cost(bags, t_arrive):
    """1.2's score: salt and time both cost - 50 per bag, 300 per second."""
    return BAG_COST * bags + SECOND_COST * t_arrive


def min_bags(litres):
    water = next(f for f in FLUIDS if f["id"] == "water")
    return next(n for n in range(0, 200) if water["rho"] + buoyancy.brine_gain(n * 1000.0 / litres) > BALL_RHO)


def floats_in(bags, litres):
    """The verdict alone: buoyancy's equilibrium (what simulate() settles to)."""
    s, liquid = brine(bags, litres)
    return buoyancy.equilibrium("sphere", BALL["d"], BALL_RHO, liquid["rho"])["state"] == "floats"


def run_salt_canal(k, fx, thresholds=None):
    """Does the rubber ball float in the canal's salt water? (buoyancy engine)"""
    s, liquid = brine(k["bags"], fx["litres"])
    solid = next(x for x in SOLIDS if x["id"] == "bouncy")
    res = buoyancy.simulate({"shape": "sphere", "size": BALL["d"] * 100.0, "g": G, "start": 10.0}, solid, liquid,
                            t_max=CANAL_WATCH)
    floats = res["viz"]["eq"]["state"] == "floats"          # == floats_in(...) (tests/test_game.py checks)
    # world path: vertical motion from the engine; the current carries the ball
    # along while it rides at the surface (a sunk ball just sits on the grate)
    surf, r = CANAL["surface"], BALL_R
    frames, x, last_t = [], CANAL["drop_x"], 0.0
    for f in res["frames"]:
        cy = surf + (f["y"] + r - buoyancy.FILL)                   # ball centre in the world
        depth = surf - cy
        x += CANAL["current"] * max(0.0, min(1.0, 1.0 - depth / 0.1)) * (f["t"] - last_t) if floats else 0.0
        last_t = f["t"]
        frames.append({"t": round(f["t"], 4), "x": round(x, 4), "y": round(cy, 4)})
        if x >= CANAL["outflow_x"]:
            break
    if floats:                                                        # keep floating to the outflow
        y_end = frames[-1]["y"]
        while x < CANAL["outflow_x"]:
            last_t += 0.05
            x = min(CANAL["outflow_x"], x + CANAL["current"] * 0.8 * 0.05)
            frames.append({"t": round(last_t, 4), "x": round(x, 4), "y": y_end})
    frames = frames[::max(1, len(frames) // 400)] + ([frames[-1]] if len(frames) > 400 else [])
    wasted = max(0.0, s - buoyancy.SALT_SAT) * fx["litres"] / 1000.0
    need = min_bags(fx["litres"])
    t_arrive = frames[-1]["t"] if floats else None
    cost = delivery_cost(k["bags"], t_arrive) if floats else None
    cost_min = (thresholds or {}).get("cost_min", cost)
    if floats:
        reason = "It floats! The salt water is %.1f kg/m³, the rubber ball %.0f kg/m³." % (liquid["rho"], BALL_RHO)
        if wasted > 0:
            reason += " (%.1f kg of salt didn't dissolve - it's just sitting on the bottom.)" % wasted
    else:
        reason = ("SPLASH... it sank to the grate: the water is %.1f kg/m³ but rubber is %.0f kg/m³."
                  % (liquid["rho"], BALL_RHO))
    return {
        "ok": floats, "reason": reason, "metric": liquid["rho"], "unit": "kg/m³", "predicted": floats,
        "score": _score(floats, SCORE_MAX - (cost - cost_min)) if floats else 0,
        "score_parts": [{"label": "salt", "value": "%d bags" % k["bags"], "note": "%d x 50 = %d" % (
                            k["bags"], BAG_COST * k["bags"])},
                        {"label": "delivery time", "value": "%.2f s" % t_arrive, "note": "%.2f x 300 = %d" % (
                            t_arrive, round(SECOND_COST * t_arrive))},
                        {"label": "cost", "value": "%d" % round(cost),
                         "note": "1000 minus how much more it cost than the cheapest delivery possible"}]
        if floats else [],
        "mastery": bool(floats and k["bags"] == need),
        "frames": frames,
        "viz": {"rho": liquid["rho"], "salt": round(s, 2), "wasted": round(wasted, 2), "color": liquid["color"],
                "t_arrive": t_arrive},
        "formula": [{"expr": "floats if rho_liquid > rho_ball",
                     "values": {"salt (g/L)": round(s, 1), "rho_liquid": liquid["rho"], "rho_ball": BALL_RHO}},
                    {"expr": "V_sub / V = rho_ball / rho_liquid",
                     "values": {"ratio": round(BALL_RHO / liquid["rho"], 3)}}],
        "lab": [{"title": "Floating & Sinking: this ball in this salt water",
                 "route": "#/buoyancy?" + _hash([("shape", "sphere"), ("material", "bouncy"), ("size", "6.0"),
                                                 ("fluid", "water"), ("salt", round(s, 2)), ("start", "10.0")])}],
    }


# ================================================================ 1.3 Camel Hump

def run_camel_hump(k, fx, thresholds=None):
    """Over the hump without flying off (energy engine, camel track)."""
    tr = energy.CamelTrack(fx["h0"], k["hump"])
    res = energy.simulate(tr, tr.START_X, BALL["mass"], energy.K["solid_ball"], fx["mu"], G, kind="camel",
                          obj="solid_ball", stop_x=TRACK_GOAL_X)
    fr = res["frames"]
    fly = next((f for f in fr if f["fly"]), None)
    near = [f for f in fr if abs(f["x"] - tr.XC) < 0.15 and not f["fly"]]
    v_top = round(min(abs(f["v"]) for f in near), 2) if near else None
    vmax = math.sqrt(G * tr.R)
    t_goal = next((f["t"] for f in fr if f["x"] >= TRACK_GOAL_X), None)
    frames = []
    for f in fr:                                       # ball centre: r out from the track, along its normal
        if fly and f["t"] >= fly["t"]:
            break
        frames.append({"t": f["t"], "x": f["x"] - math.sin(f["phi"]) * BALL_R, "y": f["y"] + math.cos(f["phi"]) * BALL_R})
        if f["t"] > 8.0:
            break
    if fly:                                            # off the top: no side walls - it falls out of the machine
        ph, v = fly["phi"], abs(fly["v"])
        x, y, vx, vy, t = fly["x"], fly["y"] + BALL_R, v * math.cos(ph), v * math.sin(ph), fly["t"]
        while y > -O_TRACK[1] and t < fly["t"] + 1.5:
            t += 1 / 60.0
            x, y, vy = x + vx / 60.0, y + vy / 60.0 - G / 7200.0, vy - G / 60.0
            frames.append({"t": round(t, 4), "x": round(x, 4), "y": round(y, 4)})
        reason = ("WHOOSH - it flew off the top at %.2f m/s: faster than sqrt(g R) = %.2f m/s, so the track "
                  "couldn't hold it." % (abs(fly["v"]), vmax))
        metric = round(abs(fly["v"]), 2)
    elif t_goal is None:
        reason = "It rolled back - the hump is higher than the ball can climb from %.2f m." % tr.f(tr.START_X)
        metric = 0.0
    else:
        reason = "Over the hump at %.2f m/s (the limit is %.2f m/s) and into the cannon after %.2f s." % (
            v_top, vmax, t_goal)
        metric = v_top
    ok = fly is None and t_goal is not None
    speed_run = (thresholds or {}).get("speed_run")
    t_best = (thresholds or {}).get("t_best", t_goal)
    return {
        "ok": ok, "reason": reason, "metric": metric, "unit": "m/s", "predicted": metric,
        "score": _score(ok, SCORE_MAX - LATE_COST * (t_goal - t_best)) if ok else 0,
        "score_parts": [{"label": "time to the cannon", "value": "%.2f s" % t_goal,
                         "note": "-50 for every 0.1 s slower than the fastest safe run"}] if ok else [],
        "mastery": bool(ok and speed_run is not None and t_goal <= speed_run + 1e-9),
        "frames": _world(frames, O_TRACK),
        "viz": {"v_top": v_top, "v_max": round(vmax, 3), "t_goal": t_goal, "flew": fly is not None},
        "formula": [{"expr": "v_top <= sqrt(g*R)", "values": {"R": tr.R, "limit": round(vmax, 2), "v_top": v_top}},
                    {"expr": "v = sqrt(2*g*h / (1 + k))",
                     "values": {"h": round(tr.f(tr.START_X) - k["hump"], 3), "k": 0.4,
                                "v (no losses)": round(math.sqrt(max(0.0, 2 * G * (tr.f(tr.START_X) - k["hump"]) / 1.4)), 2)}}],
        "lab": [{"title": "Energy Ramp: the camel track",
                 "route": "#/energy?" + _hash([("track", "camel"), ("object", "solid_ball"), ("height", fx["h0"]),
                                               ("hump", k["hump"]), ("mass", "0.5"), ("friction", fx["mu"])])}],
    }


# ================================================================ 1.4 Spring Cannon

def funnel_segments(dx, dy):
    m, th, dp = FUNNEL["mouth"], FUNNEL["throat"], FUNNEL["depth"]
    wall = dx + BANK_WALL
    return [(dx - m, dy, dx - th, dy - dp, E_FELT, "funnel"),
            (dx + m, dy, dx + th, dy - dp, E_FELT, "funnel"),
            (dx - m - 0.01, -1.2, dx - m, dy, E_WOOD, "stand"),
            (wall, dy - 0.6, wall, 5.0, E_WOOD, "bumper wall")]


def mouth_crossing(frames, dy):
    """Where the ball last came DOWN through the toy box's mouth (y = dy), interpolated."""
    x = None
    for a, b in zip(frames, frames[1:]):
        if a["y"] >= dy > b["y"]:
            u = (a["y"] - dy) / (a["y"] - b["y"])
            x = a["x"] + u * (b["x"] - a["x"])
    return x


def run_spring_cannon(k, fx, thresholds=None):
    """Spring launch into the toy box (energy + projectile with drag; bank shots off the wall)."""
    dx, dy = fx["dx"], fx["dy"]
    speed = energy.spring_launch_speed(SPRING_K, k["compression"] / 100.0, BALL["mass"], k["angle"], G)
    th = math.radians(k["angle"])
    m, thr, dp = FUNNEL["mouth"], FUNNEL["throat"], FUNNEL["depth"]
    zones = [("in", lambda x, y, vx, vy: dx - thr < x < dx + thr and dy - dp - 0.3 < y < dy - dp + 0.02),
             ("miss", lambda x, y, vx, vy: y < -MUZZLE[1] + BALL_R)]
    if speed <= 0:
        out = {"outcome": "dud", "frames": [{"t": 0.0, "x": 0.0, "y": 0.0}], "hits": []}
    else:
        out = tracer.trace(0.0, 0.0, speed * math.cos(th), speed * math.sin(th), BALL["mass"], BALL_R, BALL_K,
                           segs=funnel_segments(dx, dy), zones=zones, tmax=5.0)
    bank = any(h["name"] == "bumper wall" for h in out["hits"])
    touched = any(h["name"] in ("funnel", "stand") for h in out["hits"])
    ok = out["outcome"] == "in"
    x_cross = mouth_crossing(out["frames"], dy) if ok else None
    if ok:
        reason = "In the toy box!" + (" A trick shot off the bumper wall!" if bank else "")
    elif speed <= 0:
        reason = "The spring is too weak to even push the ball up the barrel."
    else:
        arr = tracer.trace(0.0, 0.0, speed * math.cos(th), speed * math.sin(th), BALL["mass"], BALL_R, BALL_K,
                           zones=[("arrive", lambda x, y, vx, vy: vy < 0 and y < dy)], tmax=5.0)
        lo, hi = dx - m, dx + m
        where = "your shot comes down at %.2f m; the box spans %.2f-%.2f m" % (arr["x"], lo, hi)
        if lo <= arr["x"] <= hi:
            reason = "BOING - it bounced off the rim of the toy box, it came in too %s (%s)." % (
                "flat" if k["angle"] < 40 else "close to the edge", where)
        else:
            reason = "Missed: too %s (%s)." % ("short" if arr["x"] < lo else "far", where)
    x_m = k["compression"] / 100.0
    aim = max(0.0, 1.0 - (abs(x_cross - dx) / FUNNEL["mouth"]) ** 2) if ok else 0.0
    return {
        "ok": ok, "reason": reason, "metric": round(speed, 2), "unit": "m/s", "predicted": round(speed, 2),
        "score": _score(ok, AIM_POINTS * aim + (TRICK_POINTS if bank else 0)),
        "score_parts": [{"label": "aim", "value": "%d cm from the middle" % round(100 * abs(x_cross - dx)),
                         "note": "up to 800 for dead centre (the further out, the faster it drops)"},
                        {"label": "trick shot", "value": "yes" if bank else "no",
                         "note": "+200 off the bumper wall"}] if ok else [],
        "mastery": bool(ok and bank),
        "frames": _world(out["frames"], MUZZLE),
        "viz": {"speed": round(speed, 3), "bank": bank, "touched": touched,
                "x_cross": round(x_cross, 4) if x_cross is not None else None},
        "formula": [{"expr": "1/2*k*x^2 = 1/2*m*v^2 + m*g*x*sin(angle)",
                     "values": {"k": SPRING_K, "x (m)": x_m, "m": BALL["mass"], "angle": k["angle"],
                                "v": round(speed, 2)}},
                    {"expr": "y = x*tan(angle) - g*x^2 / (2*v^2*cos(angle)^2)",
                     "values": {"x": dx, "y": dy}}],
        "lab": [{"title": "Projectile Motion: the same throw (it lands at launch height there)",
                 "route": "#/motion?" + _hash([("v0", round(speed, 2)), ("angle", k["angle"]),
                                               ("mass", BALL["mass"]), ("drag", round(BALL_K, 6)),
                                               ("wind", "0.0"), ("g", G)])}],
    }


