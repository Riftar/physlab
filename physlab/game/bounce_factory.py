# ================================================================ scores
# Every working run also gets a SCORE, 0-1000, so there is something to chase
# after "it works": 1000 is the best possible for THIS player's variant (the
# references - lowest drop, cheapest delivery, fastest run - come from the
# generated table), so scores stay fair across variants. A failed run scores 0;
# a working run never scores below SCORE_FLOOR.
SCORE_MAX, SCORE_FLOOR = kit.SCORE_MAX, kit.SCORE_FLOOR
H_COST = 400.0          # 1.1: points per metre of drop above the lowest that works (40 per 10 cm)
